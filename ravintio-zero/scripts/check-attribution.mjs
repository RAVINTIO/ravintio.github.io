#!/usr/bin/env node
// Exits 1 when any line of a file or stdin is an AI attribution line.
// Usage: node check-attribution.mjs [file]
// Exit codes: 0 clean, 1 attribution line found, 2 usage or read error.
// Prints only the line number and rule name, never the input text.
// Patterns mirror Rule 1 of ravintio-zero/hooks/commit-msg (ADR-003).
import { readFileSync } from 'node:fs';

const RULES = [
  ['host attribution line', [
    /Generated with \[?Claude Code/i,
    /Claude-Session:/i,
    /claude\.ai\/code/i,
  ]],
  ['AI attribution line', [
    /co-authored-by:.*(claude|copilot|cursor|windsurf|cline|anthrop|openai|gemini)/i,
    /co-developed with/i,
    /AI-assisted/i,
    /LLM-generated/i,
    /claude helped/i,
    /generated by (claude|copilot)/i,
  ]],
];

const args = process.argv.slice(2);
if (args.length > 1) {
  console.error('check-attribution: usage: check-attribution.mjs [file]');
  process.exit(2);
}

let text;
try {
  text = readFileSync(args.length === 1 ? args[0] : 0, 'utf8');
} catch {
  console.error('check-attribution: cannot read input');
  process.exit(2);
}

let found = false;
text.split(/\r?\n/).forEach((line, i) => {
  for (const [name, patterns] of RULES) {
    if (patterns.some((p) => p.test(line))) {
      console.error(`check-attribution: line ${i + 1}: ${name}`);
      found = true;
      return;
    }
  }
});
process.exit(found ? 1 : 0);
