#!/usr/bin/env bash
# Feature 0000031 req-001: the pack folder took its 0000031 name, with
# every live reference updated. Historical records exempt.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ZERO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO="$(cd "$ZERO_DIR/.." && pwd)"
source "$SCRIPT_DIR/helpers/assert.sh"

# Concatenated so repo-wide renames never rewrite this test's target string.
OLD_NAME="planifest""-framework"

echo "=== (a) folder is named ravintio-zero ==="
assert_equals "ravintio-zero" "$(basename "$ZERO_DIR")" "pack folder basename"
assert_equals "no" "$([ -d "$REPO/$OLD_NAME" ] && echo yes || echo no)" "old folder absent"

echo "=== (b) zero live references to the old name ==="
# plan/ is records (archive, changelog, backlog, and the change-in-progress
# artifacts that describe this very rename). CLAUDE.md is generated by setup.
# docs/decisions-index.md is a change record, exempt per the docs ADR.
# A link to the separate product's repo, ravintio/$OLD_NAME, is not a
# reference to the old folder (0000042 ADR-004).
HITS=$(grep -rn "$OLD_NAME" "$REPO" \
  --exclude-dir=.git --exclude-dir=.claude --exclude-dir=_temp \
  --exclude-dir=node_modules 2>/dev/null \
  | grep -v "$REPO/plan/\|$REPO/CLAUDE.md\|decisions-index.md" \
  | grep -v "ravintio/$OLD_NAME" | cut -d: -f1 | sort -u | wc -l | tr -d ' ')
assert_equals "0" "$HITS" "live files referencing the old name"

echo "=== (c) product.yml declares the product id and names the component ==="
# 0000033 ADR-003 v0.2.0 keeps product.yml's top-level `id` for versioning and
# archive attribution. The components[] entries keep their own `id`, because
# scripts/product-version.mjs reads them to resolve each manifest.
assert_equals "ravintio-zero" "$(grep -E '^id:' "$REPO/product.yml" | sed 's/id: *"\{0,1\}\([^"]*\)"\{0,1\}/\1/' | tr -d ' ')" \
  "top-level product id"
assert_equals "ravintio-zero" "$(grep -E '^\s+- id:' "$REPO/product.yml" | head -1 | sed 's/.*id: *"\{0,1\}\([^"]*\)"\{0,1\}/\1/' | tr -d ' ')" \
  "components[] still names the ravintio-zero component"
ORCH_SKILL="$(orch_combined "$REPO/ravintio-zero/skills/ravintio-orchestrator")"
STEP9=$(grep -E '^9\. \*\*Product id check\*\*' "$ORCH_SKILL" || true)
assert_contains "hard-stop" "$STEP9" "discovery step 9 hard-stops on a missing product id"
assert_contains "versioning" "$STEP9" "the product id prompt gives versioning as its reason"
assert_equals "0" "$(printf '%s' "$STEP9" | grep -ci telemetry || true)" "the product id prompt does not cite telemetry"
assert_equals "1" "$(grep -cE '^id:' "$REPO/ravintio-zero/templates/product.template.yml" || true)" \
  "product.template.yml declares a top-level id"

echo "=== (d) refresh script renamed and portable ==="
assert_equals "no" "$([ -f "$REPO/refresh-$OLD_NAME-dir.ps1" ] && echo yes || echo no)" "old refresh script absent"
if [ -f "$REPO/refresh-ravintio-zero-dir.ps1" ]; then
  assert_equals "0" "$(grep -c 'C:\\\\d\\\\ravintio' "$REPO/refresh-ravintio-zero-dir.ps1" || true)" "no hardcoded machine path"
  assert_contains "PSScriptRoot" "$(cat "$REPO/refresh-ravintio-zero-dir.ps1")" "derives path from script location"
else
  assert_equals "renamed-or-deleted" "missing" "refresh script neither renamed nor deleted"
fi

echo "=== (e) .gitattributes has no dead skill-sync line ==="
assert_equals "0" "$(grep -c "skill-sync" "$ZERO_DIR/.gitattributes" || true)" "skill-sync attribute gone"

print_summary
