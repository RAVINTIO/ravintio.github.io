#!/usr/bin/env bash
# 0000169 req-002: attribution-check-script (ADR-003)
# check-attribution.mjs exits 1 on an attribution line, 0 on none, 2 on a usage error.
# The hook and the script both hold the host-line patterns.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ZERO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
source "$SCRIPT_DIR/helpers/assert.sh"

CHECK="$ZERO_DIR/scripts/check-attribution.mjs"
HOOK="$ZERO_DIR/hooks/commit-msg"
TMP="$(mktemp -d -t ravintio_0000169_req002_XXXXXX)"
trap 'rm -rf "$TMP"' EXIT

# Run the check on a body. Sets CODE, OUT, ERR.
run_check() {
  printf '%s\n' "$1" > "$TMP/body.md"
  node "$CHECK" "$TMP/body.md" > "$TMP/out" 2> "$TMP/err"
  CODE=$?
  OUT="$(cat "$TMP/out")"
  ERR="$(cat "$TMP/err")"
}

echo ""
echo "=== 0000169 req-002 attribution-check-script ==="

if [ ! -f "$CHECK" ]; then
  echo "  FAIL: check-attribution.mjs is missing"; FAIL=$((FAIL+1))
fi

echo "--- Lines that must exit 1 ---"
BAD=(
  'Generated with [Claude Code](https://claude.com/claude-code)'
  '🤖 Generated with [Claude Code](https://claude.com/claude-code)'
  'Generated with Claude Code'
  'Claude-Session: abc123'
  'See https://claude.ai/code/session_01abc'
  'Co-Authored-By: Claude <noreply@anthropic.com>'
  'Co-Authored-By: Copilot <x@y.z>'
  'Co-Authored-By: Cursor <x@y.z>'
  'Co-Authored-By: Windsurf <x@y.z>'
  'Co-Authored-By: Cline <x@y.z>'
  'Co-Authored-By: Anthropic <x@y.z>'
  'Co-Authored-By: OpenAI <x@y.z>'
  'Co-Authored-By: Gemini <x@y.z>'
  'co-developed with a tool'
  'AI-assisted change'
  'LLM-generated text'
  'Claude helped here'
  'generated by Claude'
  'generated by Copilot'
)
for line in "${BAD[@]}"; do
  run_check "$(printf 'Summary\n\n%s\n' "$line")"
  assert_equals "1" "$CODE" "exit 1 for: ${line:0:40}"
done

echo "--- Output never echoes input ---"
run_check "$(printf 'ok\nok\nClaude-Session: SECRETTOKEN123\n')"
assert_contains "line 3" "$ERR" "stderr names line 3"
assert_contains "check-attribution:" "$ERR" "stderr names the script"
if printf '%s%s' "$OUT" "$ERR" | grep -q "SECRETTOKEN123\|Claude-Session"; then
  echo "  FAIL: output echoes input text"; FAIL=$((FAIL+1))
else
  echo "  PASS: output holds no input text"
fi
assert_equals "" "$OUT" "stdout is empty"

echo "--- Clean text exits 0 ---"
run_check "$(printf '## Summary\n\nThis PR adds a rule about attribution in PR bodies.\nThe attribution check runs in CI.\n')"
assert_equals "0" "$CODE" "prose mentioning attribution exits 0"
assert_equals "" "$ERR" "clean run prints nothing"

echo "--- Usage errors exit 2 ---"
node "$CHECK" "$TMP/missing.md" >/dev/null 2>&1
assert_equals "2" "$?" "missing file exits 2"
node "$CHECK" "$TMP" >/dev/null 2>&1
assert_equals "2" "$?" "directory exits 2"
node "$CHECK" a b >/dev/null 2>&1
assert_equals "2" "$?" "two arguments exit 2"

echo "--- Stdin ---"
printf 'Claude-Session: x\n' | node "$CHECK" >/dev/null 2>&1
assert_equals "1" "$?" "stdin with host line exits 1"
printf 'fine\n' | node "$CHECK" >/dev/null 2>&1
assert_equals "0" "$?" "clean stdin exits 0"

echo "--- Hook holds the host patterns (ADR-003) ---"
for pat in 'Generated with \\[?Claude Code' 'Claude-Session:'; do
  if grep -qF -- "$pat" "$HOOK"; then echo "  PASS: hook holds $pat"
  else echo "  FAIL: hook lacks $pat"; FAIL=$((FAIL+1)); fi
done
for pat in 'Generated with' 'Claude-Session:'; do
  if grep -qF -- "$pat" "$CHECK" 2>/dev/null; then echo "  PASS: script holds $pat"
  else echo "  FAIL: script lacks $pat"; FAIL=$((FAIL+1)); fi
done

echo "--- Hook rejects host lines ---"
for msg in 'feat(x): ok

Generated with [Claude Code](https://claude.com/claude-code)' 'feat(x): ok

Claude-Session: abc'; do
  printf '%s' "$msg" > "$TMP/msg"
  bash "$HOOK" "$TMP/msg" >/dev/null 2>&1
  assert_equals "1" "$?" "hook rejects: $(printf '%s' "$msg" | tail -n1 | cut -c1-30)"
done

print_summary
